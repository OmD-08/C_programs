#include<stdio.h>
int main(){
	/* 1.new 
	  Line
	  */
	  printf("1. New line (\\n):\n");
	  printf("Hello\nWorld\n\n");
	  
	  /* 2. Horizontal tab */
	  printf("2. Horizontal Tab (\\t):\n");
	  printf("Name\tAge\tCity\n");
	  printf("Vishal\t22\tNashik\n\n");
	  
	  /* 3. Backspace */
	  
	  printf("3. Backspace (\\b):\n");
	  printf("ABC\bD\n\n");
	  
	  /* 4. Carriage Return */
	  
	  printf("4. Carriage Return (\\r):\n");
	  printf("Hello\rHi\n\n");
	  
	  /* 5. Double Quote */
	  printf("5. Double Quote (\\\"):\n");
	  printf("\"C Programming\"\n\n");
	  
	  /* 6. Single Quote */
	  printf("6. Single Quote (\\'):\n");
	  printf("It\'s easy to learn C.\n\n");
	  
	  /* 7. Backslash */
	  printf("7. Backslash (\\\\):\n");
	  printf("C:\\Users\\Admin\\Documents\n\n");
	  
	  	/* 8. Alert / Beep */
	  printf("8.Alert(\\a):\n");
	  printf("\a");
	  printf("Beep Sound Triggered (if supported)\n\n");
}
